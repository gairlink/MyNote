object Lang {
    fun code(a: MainActivity): String {
        return a.getSharedPreferences("mynote", 0).getString("languageCode", "en") ?: "en"
    }
    fun str(a: MainActivity, key: String): String {
        val c = code(a)
        val m = when (c) {
            "en" -> en
            "it" -> it
            "ru" -> ru
            "tr" -> tr
            else -> ka
        }
        return m[key] ?: ka[key] ?: key
    }
